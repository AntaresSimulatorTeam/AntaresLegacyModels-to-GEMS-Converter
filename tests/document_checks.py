"""Generates the list of tests in CHECKS.md from the docstrings of the tests.

Each test states, in its docstring, what it guarantees; each test module, in
its own docstring, what the file covers; each documented test directory, in the
docstring of its ``__init__.py``, a title (first line) and an introduction.
This script writes them between the markers of CHECKS.md; the text around the
markers is written by hand. Run it after adding, removing or changing a test of
a documented directory:

    uv run python tests/document_checks.py

``tests/consistency/test_checks_doc.py`` fails when CHECKS.md is out of date or
when a test of a documented directory has no docstring.
"""

import ast
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TESTS_DIR = REPO_ROOT / "tests"
CHECKS_DOC = REPO_ROOT / "CHECKS.md"

# Test directories listed in CHECKS.md, in this order. Every test module and
# test in them must have a docstring. Add a directory once it is documented.
DOCUMENTED_DIRS = ["consistency"]

BEGIN_MARKER = (
    "<!-- BEGIN GENERATED by tests/document_checks.py from the test docstrings:"
    " do not edit by hand -->"
)
END_MARKER = "<!-- END GENERATED -->"

REGENERATE_COMMAND = "uv run python tests/document_checks.py"


def modules_of(directory: str) -> list[Path]:
    return sorted((TESTS_DIR / directory).rglob("test_*.py"))


def tests_of(module: ast.Module) -> list[ast.FunctionDef]:
    """The tests of a module, as pytest collects them: functions named test_*,
    and methods named test_* of classes named Test*."""
    tests = []
    for node in module.body:
        if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
            tests.append(node)
        elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            tests += [
                method
                for method in node.body
                if isinstance(method, ast.FunctionDef)
                and method.name.startswith("test_")
            ]
    return tests


def parse(path: Path) -> ast.Module:
    return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def missing_docstrings(path: Path) -> list[str]:
    """The module (as "module docstring") and tests of a file with no docstring."""
    module = parse(path)
    missing = [] if ast.get_docstring(module) else ["module docstring"]
    return missing + [
        test.name for test in tests_of(module) if not ast.get_docstring(test)
    ]


def paragraphs(docstring: str | None) -> list[str]:
    """The paragraphs of a docstring, each on one line."""
    if not docstring:
        return []
    return [
        " ".join(line.strip() for line in paragraph.splitlines())
        for paragraph in docstring.split("\n\n")
        if paragraph.strip()
    ]


def table_cell(docstring: str | None) -> str:
    text = "<br>".join(paragraphs(docstring)) or "_no docstring_"
    return text.replace("|", "\\|")


def relative(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def directory_section(directory: str) -> list[str]:
    init_file = TESTS_DIR / directory / "__init__.py"
    title, *introduction = paragraphs(ast.get_docstring(parse(init_file))) or [
        directory
    ]
    lines = [f"### {title} (`tests/{directory}/`)", ""]
    for paragraph in introduction:
        lines += [paragraph, ""]

    for path in modules_of(directory):
        module = parse(path)
        module_paragraphs = paragraphs(ast.get_docstring(module))
        summary = module_paragraphs[0] if module_paragraphs else "_no docstring_"
        lines += [
            f"#### [`{path.name}`]({relative(path)})",
            "",
            summary,
            "",
            "| Test | Guarantee |",
            "|---|---|",
        ]
        lines += [
            f"| `{test.name}` | {table_cell(ast.get_docstring(test))} |"
            for test in tests_of(module)
        ]
        lines.append("")
    return lines


def undocumented_dirs() -> list[str]:
    return sorted(
        path.name
        for path in TESTS_DIR.iterdir()
        if path.is_dir() and path.name not in DOCUMENTED_DIRS and modules_of(path.name)
    )


def generated_text() -> str:
    lines = [BEGIN_MARKER, ""]
    for directory in DOCUMENTED_DIRS:
        lines += directory_section(directory)
    others = ", ".join(f"`tests/{directory}/`" for directory in undocumented_dirs())
    if others:
        lines += [
            f"Not listed here yet: {others}. See the Test Architecture section of"
            " [AGENTS.md](AGENTS.md).",
            "",
        ]
    lines.append(END_MARKER)
    return "\n".join(lines)


def updated_checks_doc(current: str) -> str:
    """CHECKS.md with the text between its markers regenerated."""
    begin = current.find(BEGIN_MARKER)
    end = current.find(END_MARKER)
    if begin == -1 or end < begin:
        raise ValueError(
            f"{relative(CHECKS_DOC)} must contain the lines\n{BEGIN_MARKER}\n"
            f"{END_MARKER}\nin this order"
        )
    return current[:begin] + generated_text() + current[end + len(END_MARKER) :]


def main() -> None:
    current = CHECKS_DOC.read_text(encoding="utf-8")
    CHECKS_DOC.write_text(updated_checks_doc(current), encoding="utf-8")
    print(f"{relative(CHECKS_DOC)} updated")


if __name__ == "__main__":
    main()
